package com.osrsaibuddy;

import com.google.gson.Gson;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.StandardCopyOption;
import java.time.Instant;
import java.util.HashSet;
import java.util.Set;
import java.util.UUID;
import java.util.stream.Collectors;
import java.util.stream.Stream;
import net.runelite.client.util.Filepath;

/** Readable derived copies; chats.json remains the authoritative restore file. */
final class ChatTranscripts
{
    static final String FOLDER = "conversations";

    static void sync(Filepath root, Gson gson, String json) throws IOException
    {
        ChatStore.Saved saved = gson.fromJson(json, ChatStore.Saved.class);
        if (saved == null || saved.chats == null) { throw new IOException("Invalid saved conversations"); }
        Filepath folder = root.joinSegment(FOLDER);
        folder.createDirectories();
        Set<String> keep = new HashSet<>();
        StringBuilder index = new StringBuilder("# Saved Conversations\n\nGenerated by OSRS AI Buddy. These readable copies can contain personal chat and account details.\n\nManage chats in Buddy; edits here do not change the saved conversation.\n\n");
        for (ChatStore.SavedChat chat : saved.chats)
        {
            // Never use user-supplied titles or saved IDs as filesystem paths.
            String filename = "buddy-" + UUID.nameUUIDFromBytes(String.valueOf(chat.id).getBytes(StandardCharsets.UTF_8)) + ".md";
            keep.add(filename);
            String title = chat.name == null ? "Conversation" : chat.name;
            index.append("- [").append(title.replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]").replace('\n', ' ').replace('\r', ' '))
                .append("](").append(filename).append(")\n");
            StringBuilder text = new StringBuilder("# ").append(title.replace('\n', ' ').replace('\r', ' ')).append("\n\n");
            if (chat.createdAt > 0) { text.append("Created: ").append(Instant.ofEpochMilli(chat.createdAt)).append("\n\n"); }
            if (chat.leftOut > 0) { text.append("Earlier messages omitted from saved history: ").append(chat.leftOut).append("\n\n"); }
            if (chat.summary != null && !chat.summary.isEmpty()) { text.append("## Earlier Conversation Summary\n\n").append(chat.summary).append("\n\n"); }
            if (chat.messages != null) for (ChatStore.SavedMessage message : chat.messages)
            {
                text.append("## ").append("USER".equals(message.role) ? "You" : "ASSISTANT".equals(message.role) ? "Buddy" : message.role)
                    .append(" · ").append(Instant.ofEpochMilli(message.time)).append("\n\n")
                    .append(message.text == null ? "" : message.text).append("\n\n");
                if (message.context != null) { text.append("### Shared Account Context\n\n").append(message.context).append("\n\n"); }
                if (message.activity != null && !message.activity.isEmpty()) { text.append("### Lookups and Sharing\n\n"); for (String activity : message.activity) { text.append("- ").append(activity).append('\n'); } text.append('\n'); }
            }
            replace(folder, filename, text.toString());
        }
        replace(folder, "README.md", index.toString());
        // Only remove our generated filenames, never other files a user put here.
        try (Stream<Filepath> files = folder.walk(1))
        {
            for (Filepath file : files.filter(f -> f.isFile() && f.getFileName().matches("buddy-[0-9a-f-]{36}\\.md") && !keep.contains(f.getFileName())).collect(Collectors.toList()))
            { file.deleteIfExists(); }
        }
    }

    private static void replace(Filepath folder, String name, String text) throws IOException
    {
        Filepath temporary = folder.createTempFile("transcript-", ".tmp");
        try { temporary.write(text); temporary.moveTo(folder.joinSegment(name), StandardCopyOption.REPLACE_EXISTING); }
        finally { temporary.deleteIfExists(); }
    }
}
